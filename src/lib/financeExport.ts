import { saveAs } from 'file-saver'
import { loadCompanyLogoImage, type ExportCompanyHeader } from './excelExport'

export type FinanceExportLanguage = 'en' | 'pt' | 'bi'

export type FinanceExportCompany = ExportCompanyHeader

export type FinanceExportCounterparty = {
  kind: 'customer' | 'supplier'
  name: string
  code?: string | null
  taxId?: string | null
  contactName?: string | null
  email?: string | null
  phone?: string | null
  address?: string | null
  source: 'document_snapshot' | 'master'
}

export type FinanceExportBank = {
  name: string
  bankName?: string | null
  maskedAccountNumber?: string | null
  operatingCurrency?: string | null
  swift?: string | null
  nib?: string | null
}

export type FinanceExportContext = {
  title: string
  subtitle?: string
  language: FinanceExportLanguage
  generatedAt: string
  generatedBy?: string | null
  company: FinanceExportCompany
  counterparty?: FinanceExportCounterparty | null
  counterpartyScope?: string | null
  bank?: FinanceExportBank | null
  period?: { from?: string | null; to?: string | null }
  filters?: string[]
  baseCurrency: string
  disclaimer?: string | null
}

export type FinanceExportCell = string | number | boolean | null | undefined

export type FinanceExportColumn = {
  key: string
  label: string
  type?: 'text' | 'number' | 'currency' | 'date' | 'status'
  width?: number
}

export type FinanceExportSummaryItem = {
  label: string
  value: FinanceExportCell
  type?: 'text' | 'number' | 'currency'
}

export type FinanceExportSection = {
  title: string
  columns: FinanceExportColumn[]
  rows: Array<Record<string, FinanceExportCell>>
  totals?: Array<Record<string, FinanceExportCell>>
}

export type FinanceExportModel = {
  filename: string
  context: FinanceExportContext
  summary?: FinanceExportSummaryItem[]
  sections: FinanceExportSection[]
  orientation?: 'portrait' | 'landscape'
}

